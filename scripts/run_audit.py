"""Phase 1: load, combine, clean and deduplicate the data, and write the data audit.

Usage: python scripts/run_audit.py [--config configs/default.yaml]
"""
import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src import data  # noqa: E402
from src.config import ROOT, load_config, save_run_info, set_seed  # noqa: E402
from src.split import make_splits  # noqa: E402

# Facts from the spec (section 3.2), written from memory; we check each one against the data.
EXPECTED_ROWS = {"UNSW_NB15_training-set.csv": 175341, "UNSW_NB15_testing-set.csv": 82332}
EXPECTED_COLS = (
    "id dur proto service state spkts dpkts sbytes dbytes rate sttl dttl sload dload sloss dloss "
    "sinpkt dinpkt sjit djit swin stcpb dtcpb dwin tcprtt synack ackdat smean dmean trans_depth "
    "response_body_len ct_srv_src ct_state_ttl ct_dst_ltm ct_src_dport_ltm ct_dst_sport_ltm "
    "ct_dst_src_ltm is_ftp_login ct_ftp_cmd ct_flw_http_mthd ct_src_ltm ct_srv_dst is_sm_ips_ports "
    "attack_cat label"
).split()
EXPECTED_CLASSES = {"Normal", "Fuzzers", "Analysis", "Backdoor", "DoS", "Exploits", "Generic",
                    "Reconnaissance", "Shellcode", "Worms"}
FORBIDDEN_COLS = {"srcip", "sport", "dstip", "dsport", "stime", "ltime"}  # IPs, ports, timestamps
SKEW_COLS = ["dur", "spkts", "dpkts", "sbytes", "dbytes", "rate", "sload", "dload",
             "smean", "dmean", "response_body_len", "sinpkt", "dinpkt"]


def md_table(df, index=True):
    """Small markdown table writer (avoids an extra dependency)."""
    if index:
        df = df.reset_index()
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        cells = [f"{v:,.4g}" if isinstance(v, float) else (f"{v:,}" if isinstance(v, int) else str(v)) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def check_facts(raw):
    """Compare the real data with section 3.2 of the spec. Returns lines of markdown."""
    out = []

    def check(ok, text):
        out.append(f"- {'OK' if ok else '**DIFFERS**'}: {text}")

    for name, expected in EXPECTED_ROWS.items():
        n = int((raw["source_file"] == name).sum())
        check(n == expected, f"`{name}` has {n:,} rows (spec says {expected:,})")
    if all(int((raw["source_file"] == n).sum()) != e for n, e in EXPECTED_ROWS.items()):
        swapped = all(int((raw["source_file"] == n).sum()) == e
                      for n, e in zip(EXPECTED_ROWS, reversed(list(EXPECTED_ROWS.values()))))
        if swapped:
            out.append("  - The two counts are swapped: the file named *training* is the smaller one. "
                       "This is a known quirk of the official release. It does not matter here because we combine both files.")

    cols = [c for c in raw.columns if c != "source_file"]
    missing, extra = set(EXPECTED_COLS) - set(cols), set(cols) - set(EXPECTED_COLS)
    check(not missing and not extra,
          f"{len(cols)} columns (spec: {len(EXPECTED_COLS)}); missing: {sorted(missing) or 'none'}; extra: {sorted(extra) or 'none'}")
    bad = FORBIDDEN_COLS & {c.lower() for c in cols}
    check(not bad, f"no IP address, port or timestamp columns (found: {sorted(bad) or 'none'})")

    classes = set(raw["attack_cat"].astype(str).str.strip())
    check(classes == EXPECTED_CLASSES,
          f"attack_cat has {len(classes)} values; not in spec: {sorted(classes - EXPECTED_CLASSES) or 'none'}; "
          f"in spec but absent: {sorted(EXPECTED_CLASSES - classes) or 'none'}")
    n_proto = raw["proto"].nunique()
    check(n_proto >= 100, f"`proto` has {n_proto} distinct values (spec: 100+)")
    check("-" in set(raw["service"]), "`service` uses `-` for unknown "
          f"({int((raw['service'] == '-').sum()):,} rows)")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/default.yaml")
    args = ap.parse_args()

    cfg = load_config(args.config)
    set_seed(cfg["seed"])
    data_dir = ROOT / cfg["data_dir"]
    data.check_raw_files(data_dir)

    md = ["# Data audit (generated by `scripts/run_audit.py`)", "",
          f"Config: `{Path(cfg['config_path']).name}`, seed {cfg['seed']}, conflict_policy `{cfg['conflict_policy']}`.", ""]

    # ---- Load and combine
    raw = data.load_raw(data_dir)
    steps = [("loaded (both files combined)", len(raw))]

    md += ["## 1. Facts from the spec checked against the data", ""] + check_facts(raw) + [""]

    # ---- Labels
    raw, changes = data.normalise_labels(raw)
    md += ["## 2. Label cleaning", "",
           f"- attack_cat changes (strip spaces, spelling): {changes or 'none'}"]
    bad = data.label_mismatches(raw)
    md.append(f"- `label` vs `attack_cat` mismatches: {len(bad):,}")
    if len(bad) > 10:
        # Agreed rule: more than 10 mismatches means something is off, so stop and show examples.
        print(f"STOP: {len(bad)} label/attack_cat mismatches. Examples:")
        print(bad[["source_file", "id", "attack_cat", "label"]].head(20).to_string())
        sys.exit(2)
    # Trust attack_cat: rebuild label from it.
    raw["label"] = (raw["attack_cat"] != "Normal").astype(int)
    md.append("- `label` is rebuilt from `attack_cat` (Normal = 0, else 1), so the two always agree.")
    md.append("")

    # ---- Drop id (row index, not a feature)
    raw = raw.drop(columns=["id"])

    # ---- Deduplicate
    counts_before = data.class_counts(raw)
    clean, info = data.deduplicate(raw, policy=cfg["conflict_policy"])
    counts_after = data.class_counts(clean)
    steps += [("after removing exact duplicates", info["rows_after_exact"]),
              (f"after conflicting duplicates ({info['policy']})", info["rows_after_conflicts"])]

    md += ["## 3. Row counts after each cleaning step", "",
           md_table(pd.DataFrame(steps, columns=["step", "rows"]), index=False), "",
           f"Duplicates are judged on the {len(data.feature_columns(raw))} feature columns only "
           "(`id`, `source_file`, `label`, `attack_cat` excluded). "
           f"Exact duplicates removed: {info['exact_removed']:,}. Rows removed by the conflict step: {info['conflict_removed']:,}.", ""]

    cls = pd.DataFrame({"before_dedup": counts_before, "after_dedup": counts_after}).fillna(0).astype(int)
    cls["kept_%"] = (100 * cls["after_dedup"] / cls["before_dedup"]).round(1)
    cls = cls.sort_values("before_dedup", ascending=False)
    md += ["## 4. Class counts before and after dedup", "", md_table(cls), ""]

    md += ["## 5. Conflicting duplicates", "",
           f"- Conflicting groups (same features, different attack_cat, after exact dedup): {info['conflict_groups']:,}",
           f"- Rows in those groups: {info['conflict_rows']:,}", "",
           "Label sets that clash (number of groups):", ""]
    sets = pd.Series(info["conflict_label_sets"], name="groups").rename_axis("labels")
    md += [md_table(sets.to_frame()), "",
           "Original rows (before exact dedup) per class that sit in conflicting groups:", "",
           md_table(pd.Series(info["conflict_orig_rows_by_class"], name="rows").rename_axis("attack_cat")
                    .sort_values(ascending=False).to_frame()), ""]

    # ---- Columns, dtypes, missing values
    col_info = pd.DataFrame({"dtype": clean.dtypes.astype(str), "missing": clean.isna().sum()})
    md += ["## 6. Columns, dtypes and missing values (clean data)", "",
           f"Total missing values: {int(col_info['missing'].sum()):,}", "",
           md_table(col_info.rename_axis("column")), ""]

    # ---- Text columns
    md += ["## 7. Text columns", ""]
    for c in data.TEXT_COLS:
        vc = clean[c].value_counts()
        top = ", ".join(f"`{k}` {v:,}" for k, v in vc.head(12).items())
        md.append(f"- `{c}`: {len(vc)} distinct values. Most common: {top}")
    md.append("")

    # ---- Numeric skew
    num = data.numeric_summary(clean, data.numeric_columns(clean))
    md += ["## 8. Numeric summaries (clean data)", "",
           "Byte, packet, load and duration features: the median is tiny compared with the max (heavy right skew), "
           "which is why Phase 3 applies log1p before scaling.", "",
           md_table(num[num["column"].isin(SKEW_COLS)], index=False), "",
           "All numeric columns (the `negatives` column matters for log1p in Phase 3):", "",
           md_table(num, index=False), ""]

    # ---- Split preview (no class hidden)
    sp = make_splits(clean, hidden=None, split_cfg=cfg["split"], seed=cfg["seed"])
    prev = pd.DataFrame({k: clean.loc[v, "attack_cat"].value_counts() for k, v in sp.items()}).fillna(0).astype(int)
    prev = prev.loc[cls.index.intersection(prev.index)]
    prev.loc["TOTAL"] = prev.sum()
    md += ["## 9. Split preview after dedup (no class hidden)", "",
           f"Stratified by attack_cat, fractions {cfg['split']}, seed {cfg['seed']}. "
           "In each LOAO round the hidden class moves wholly into test; known classes keep these sizes.", "",
           md_table(prev.rename_axis("attack_cat")), "",
           f"Smallest possible pooled p-value at this size: 1/(n_final + 1) = 1/{prev.loc['TOTAL', 'calib_final'] + 1:,} "
           f"= {1 / (prev.loc['TOTAL', 'calib_final'] + 1):.2e}, far below the smallest alpha (0.005).", ""]

    # ---- Save
    out_dir = ROOT / cfg["processed_dir"]
    out_dir.mkdir(parents=True, exist_ok=True)
    clean.to_parquet(out_dir / "clean.parquet", index=False)
    audit_dir = ROOT / "outputs" / "audit"
    audit_dir.mkdir(parents=True, exist_ok=True)
    (audit_dir / "data_audit.md").write_text("\n".join(md), encoding="utf-8")
    save_run_info(cfg, "audit")

    print("\n".join(md[:3]))
    print(f"Saved {out_dir / 'clean.parquet'} ({len(clean):,} rows) and {audit_dir / 'data_audit.md'}")


if __name__ == "__main__":
    main()
